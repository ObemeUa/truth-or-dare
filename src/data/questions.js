function getRandomQuestion(type, adultMode) {
  let questionArray;
  let typeKey;

  if (adultMode) {
    if (type === 'truth') {
      questionArray = truth18;
      typeKey = 'truth18';
    } else {
      questionArray = dare18;
      typeKey = 'dare18';
    }
  } else {
    if (type === 'truth') {
      questionArray = truth;
      typeKey = 'truth';
    } else {
      questionArray = dare;
      typeKey = 'dare';
    }
  }

  const unusedQuestions = questionArray.filter(q => !usedQuestions[typeKey].has(q));

  if (unusedQuestions.length === 0) {
    usedQuestions[typeKey].clear();
    const randomIndex = Math.floor(Math.random() * questionArray.length);
    const question = questionArray[randomIndex];
    usedQuestions[typeKey].add(question);
    return question;
  }

  const randomIndex = Math.floor(Math.random() * unusedQuestions.length);
  const question = unusedQuestions[randomIndex];
  usedQuestions[typeKey].add(question);

  return question;
}

function resetUsedQuestions() {
  usedQuestions.truth.clear();
  usedQuestions.dare.clear();
  usedQuestions.truth18.clear();
  usedQuestions.dare18.clear();
}

